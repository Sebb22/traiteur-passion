CREATE TABLE IF NOT EXISTS seasonal_ambiences (
    id TINYINT UNSIGNED NOT NULL PRIMARY KEY,
    enabled TINYINT(1) NOT NULL DEFAULT 0,
    starts_at DATETIME NULL,
    ends_at DATETIME NULL,
    snowflake_count SMALLINT UNSIGNED NOT NULL DEFAULT 35,
    color VARCHAR(32) NOT NULL DEFAULT '#ffffff',
    opacity_min DECIMAL(3,2) NOT NULL DEFAULT 0.25,
    opacity_max DECIMAL(3,2) NOT NULL DEFAULT 0.75,
    speed_min DECIMAL(4,2) NOT NULL DEFAULT 0.35,
    speed_max DECIMAL(4,2) NOT NULL DEFAULT 1.10,
    wind_min DECIMAL(4,2) NOT NULL DEFAULT -0.20,
    wind_max DECIMAL(4,2) NOT NULL DEFAULT 0.60,
    mobile_enabled TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

